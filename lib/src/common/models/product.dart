class Product {
  final String id;
  final String name;
  final double price;
  final int moq;
  final String vendorId;
  final String category;
  final String imageUrl;

  Product({
    required this.id,
    required this.name,
    required this.price,
    required this.moq,
    required this.vendorId,
    required this.category,
    required this.imageUrl,
  });
}
